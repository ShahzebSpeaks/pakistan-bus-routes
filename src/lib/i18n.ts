export const DICTS: Record<Lang, Dict> = { en, ur };

/** Pick the Urdu name when the UI is in Urdu and one exists. */
export function localName(lang: Lang, item: { name: string; name_ur?: string }) {
  return lang === 'ur' && item.name_ur ? item.name_ur : item.name;
}

/** Localised "12 min" / "1 h 5 min". */
export function fmtMinutes(t: Dict, lang: Lang, minutes: number) {
  const m = Math.max(1, Math.round(minutes));
  const h = Math.floor(m / 60);
  const r = m % 60;
  const s = h ? `${h} ${t.hours_short}${r ? ` ${r} ${t.min}` : ''}` : `${m} ${t.min}`;
  return num(lang, s);
}

/** Localised "350 m" / "2.4 km". */
export function fmtDistance(t: Dict, lang: Lang, metres: number) {
  const s = metres < 950 ? `${Math.round(metres / 10) * 10} ${t.metres}` : `${(metres / 1000).toFixed(metres < 10_000 ? 1 : 0)} ${t.km}`;
  return num(lang, s);
}

const urDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
export function num(lang: Lang, n: number | string) {
  const s = String(n);
  return lang === 'ur' ? s.replace(/\d/g, (d) => urDigits[+d]) : s;
}
